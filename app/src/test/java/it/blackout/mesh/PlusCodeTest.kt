    @Test fun encodeIntegersMatchesExactly() = encoding.forEach { r ->
        assertEquals(r.toString(), r[5], PlusCode.encodeIntegers(r[2].toLong(), r[3].toLong(), r[4].toInt()))
    }

    /** Like the reference's own tests: degrees may land one integer step low (floating point), so a few codes differ. */
    @Test fun encodeDegrees() {
        var differ = 0
        for (r in encoding) {
            val (la, ln) = PlusCode.toIntegers(r[0].toDouble(), r[1].toDouble())
            assertTrue(r.toString(), kotlin.math.abs(la - r[2].toLong()) <= 1 && kotlin.math.abs(ln - r[3].toLong()) <= 1)
            val code = PlusCode.encode(r[0].toDouble(), r[1].toDouble(), r[4].toInt())
            assertEquals(PlusCode.encodeIntegers(la, ln, r[4].toInt()), code)
            if (code != r[5]) differ++
        }
        assertEquals(3, differ) // 40.6,129.7 / 2.5,-64.23 / -34.45,-93.719: the same on the iPhone
    }

    @Test fun decode() = decoding.forEach { r ->
        val a = PlusCode.decode(r[0])!!
        assertEquals(r.toString(), r[1].toInt(), a.length)
        assertEquals(r.toString(), r[2].toDouble(), a.latLo, 1e-10)
        assertEquals(r.toString(), r[3].toDouble(), a.lonLo, 1e-10)
        assertEquals(r.toString(), r[4].toDouble(), a.latHi, 1e-10)
        assertEquals(r.toString(), r[5].toDouble(), a.lonHi, 1e-10)
    }

    @Test fun validity() {
        for (c in listOf("8FQFF57R+M2", "8fqff57r+m2", "8FQFF57R+M2J", "8FQF0000+", "8FQFF57R+", "F57R+M2", "WC2345+G6g"))
            assertTrue(c, PlusCode.isValid(c))
        for (c in listOf("", "8FQFF57R", "8FQFF57R+M", "8FQFF57R++M2", "8FQF0000+M2", "8FQF00R5+", "8FQFF57R+M2O", "8FQFF57R1+M2",
                         "ZFQFF57R+M2", "8FQFF57R+M2ß", "WC2345+G6g0"))
            assertFalse(c, PlusCode.isValid(c))
        assertTrue(PlusCode.isFull("8FQFF57R+M2")); assertFalse(PlusCode.isFull("F57R+M2"))
        assertNull(PlusCode.decode("F57R+M2")) // short codes need a reference place: not supported
        assertNull(PlusCode.decode("hello"))
        assertNull(PlusCode.encode(Double.NaN, 0.0)); assertNull(PlusCode.encode(0.0, Double.POSITIVE_INFINITY))
        assertNull(PlusCode.encode(0.0, 0.0, 9)); assertNull(PlusCode.encode(0.0, 0.0, 1))
        assertEquals("8FQFF57R+M2", Spot(45.4642, 9.19, 12).plusCode)
        assertNull(Spot(95.0, 9.19).plusCode)
    }

    @Test fun roundTripStaysInsideTheArea() {
        val rnd = java.util.Random(7)
        repeat(2_000) {
            val lat = rnd.nextDouble() * 180 - 90; val lon = rnd.nextDouble() * 360 - 180
            val a = PlusCode.decode(PlusCode.encode(lat, lon)!!)!!
            assertTrue(lat >= a.latLo && lat < a.latHi + 1e-12 && lon >= a.lonLo && lon < a.lonHi + 1e-12)
            assertEquals(PlusCode.encode(lat, lon), PlusCode.encode(a.center.lat, a.center.lon))
        }
    }
